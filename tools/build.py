"""Assemble a script.json into Remotion timeline props and render with the engine.

A project directory looks like:
    <project>/
      script.json          shots[], music mood, brand (generated by `pdd new`)
      assets/              clips referenced by shot.src / srcL / srcR (relative names)
      audio/               s<n>.mp3 + manifest.json   (from vo.py)        [optional]
      music.mp3            background bed              (from music.py)     [optional]

    python tools/build.py --project projects/my-demo
    python tools/build.py --project projects/my-demo --dry   # write props.json, skip render

Each shot maps to a Timeline Segment. When a shot has a `vo` line, the on-screen
caption defaults to that exact line (subtitles match the narration) and the shot's
duration is stretched to fit the spoken audio.
"""
